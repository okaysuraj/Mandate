// Preserve every Google Fonts language range while removing external stylesheet requests.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),directory=path.join(root,'frontend/public/fonts');
const metadataFile=path.join(directory,'text-fonts.json');
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
async function download(url){const response=await fetch(url,{signal:AbortSignal.timeout(30000),headers:{'User-Agent':'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'}});if(!response.ok)throw new Error('Font source returned '+response.status);return response;}
(async()=>{
 if(process.argv.includes('--check')){
  const metadata=JSON.parse(fs.readFileSync(metadataFile,'utf8'));
  for(const font of metadata.fonts)if(hash(fs.readFileSync(path.join(directory,font.file)))!==font.sha256)throw new Error('Text font checksum mismatch');
  console.log('Text fonts verified: '+metadata.fonts.length+' language subsets');return;
 }
 const source='https://fonts.googleapis.com/css2?family=Hanken+Grotesk:wght@400..800&family=JetBrains+Mono:wght@400..700&display=swap';
 let css=await (await download(source)).text();const fonts=[],preloads=[];
 fs.mkdirSync(directory,{recursive:true});
 for(const match of css.matchAll(/\/\* ([^*]+) \*\/\s*@font-face\s*\{([^}]+)\}/g)){
  const range=match[1],family=match[2].match(/font-family:\s*'([^']+)'/)?.[1],url=match[2].match(/url\(([^)]+)\)/)?.[1];
  if(!family||!url||new URL(url).hostname!=='fonts.gstatic.com')throw new Error('Unexpected font stylesheet');
  const bytes=Buffer.from(await (await download(url)).arrayBuffer()),sha256=hash(bytes);
  const file=family.toLowerCase().replaceAll(' ','-')+'-'+range+'-'+sha256.slice(0,12)+'.woff2';
  fs.writeFileSync(path.join(directory,file),bytes);fonts.push({family,range,file,bytes:bytes.length,sha256});
  css=css.replaceAll(url,'/fonts/'+file);if(range==='latin')preloads.push(file);
 }
 if(fonts.length!==10)throw new Error('Review changed font language ranges before updating');
 for(const family of ['hankengrotesk','jetbrainsmono'])fs.writeFileSync(path.join(directory,'LICENSE-'+family+'.txt'),await (await download('https://raw.githubusercontent.com/google/fonts/main/ofl/'+family+'/OFL.txt')).text());
 fs.mkdirSync(path.join(root,'frontend/src/assets'),{recursive:true});
 fs.writeFileSync(path.join(root,'frontend/src/assets/text-fonts.css'),'/* Generated by scripts/update-text-fonts.cjs; SIL Open Font License 1.1. */\n'+css);
 fs.writeFileSync(metadataFile,JSON.stringify({source,license:'OFL-1.1',fonts},null,2)+'\n');
 const entry=path.join(root,'frontend/index.html');let html=fs.readFileSync(entry,'utf8');
 const links=preloads.map(file=>'    <link rel="preload" href="/fonts/'+file+'" as="font" type="font/woff2" crossorigin />').join('\n');
 html=html.replace(/    <!-- Text font preloads -->[\s\S]*?    <!-- \/Text font preloads -->/,'    <!-- Text font preloads -->\n'+links+'\n    <!-- /Text font preloads -->');
 fs.writeFileSync(entry,html);console.log('Generated '+fonts.length+' text font subsets, '+fonts.reduce((sum,font)=>sum+font.bytes,0)+' bytes; latin subsets are preloaded');
})().catch(error=>{console.error(error.message);process.exitCode=1;});
