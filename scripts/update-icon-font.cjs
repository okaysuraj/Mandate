// Self-host only the Material Symbols used by the web app. Updates need network;
// --check is offline and prevents shipping a new icon without updating the subset.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {execFileSync}=require('node:child_process');
const parser=require('../frontend/node_modules/@babel/parser');
const root=path.resolve(__dirname,'..'),directory=path.join(root,'frontend/public/fonts');
const metadataFile=path.join(directory,'material-symbols.json');
function usedNames(codepoints) {
  const available=new Set(codepoints.trim().split('\n').map(line=>line.split(' ')[0]));
  const used=new Set();
  const files=execFileSync('rg',['--files','frontend/src'],{cwd:root,encoding:'utf8'}).trim().split(/\r?\n/).filter(file=>/\.(js|jsx)$/.test(file));
  function walk(node) {
    if(!node||typeof node!=='object')return;
    if(node.type==='StringLiteral'||node.type==='JSXText') {const name=node.value.trim();if(available.has(name))used.add(name);}
    for(const [key,value]of Object.entries(node)){if(['loc','start','end','extra'].includes(key))continue;if(Array.isArray(value))value.forEach(walk);else if(value&&typeof value==='object')walk(value);}
  }
  for(const file of files)walk(parser.parse(fs.readFileSync(path.join(root,file),'utf8'),{sourceType:'module',plugins:['jsx']}));
  return [...used].sort();
}
async function download(url) {
  const result=await fetch(url,{signal:AbortSignal.timeout(30000),headers:{'User-Agent':'Mozilla/5.0'}});
  if(!result.ok)throw new Error('Font source returned '+result.status);
  return result;
}
(async()=>{
  if(process.argv.includes('--check')) {
    const metadata=JSON.parse(fs.readFileSync(metadataFile,'utf8'));
    const expected=usedNames(fs.readFileSync(path.join(directory,'material-symbols.codepoints'),'utf8'));
    const missing=expected.filter(name=>!metadata.icons.includes(name));
    if(missing.length)throw new Error('Run node scripts/update-icon-font.cjs to include icons: '+missing.join(', '));
    const font=fs.readFileSync(path.join(directory,metadata.file));
    if(crypto.createHash('sha256').update(font).digest('hex')!==metadata.sha256)throw new Error('Icon font checksum mismatch');
    console.log('Icon subset verified: '+metadata.icons.length+' symbols, '+font.length+' bytes');
    return;
  }
  const codepointsSource='https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsOutlined%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints';
  const codepoints=await (await download(codepointsSource)).text();
  const icons=usedNames(codepoints);
  const cssUrl='https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:wght,FILL@500,0..1&icon_names='+icons.join(',')+'&display=block';
  const css=await (await download(cssUrl)).text();
  const fontUrl=css.match(/src:\s*url\(([^)]+)\)/)?.[1];
  if(!fontUrl||new URL(fontUrl).hostname!=='fonts.gstatic.com')throw new Error('Unexpected Google Fonts response');
  const font=Buffer.from(await (await download(fontUrl)).arrayBuffer());
  const sha256=crypto.createHash('sha256').update(font).digest('hex'),file='material-symbols-'+sha256.slice(0,12)+'.woff2';
  const license=await (await download('https://raw.githubusercontent.com/google/material-design-icons/master/LICENSE')).text();
  fs.mkdirSync(directory,{recursive:true});fs.writeFileSync(path.join(directory,file),font);
  fs.writeFileSync(path.join(directory,'material-symbols.codepoints'),codepoints);
  fs.writeFileSync(path.join(directory,'LICENSE-Material-Symbols.txt'),license);
  fs.writeFileSync(metadataFile,JSON.stringify({file,sha256,bytes:font.length,icons,source:cssUrl,codepointsSource,license:'Apache-2.0'},null,2)+'\n');
  const stylesheet=path.join(root,'frontend/src/index.css');let source=fs.readFileSync(stylesheet,'utf8');
  const declaration="/* Material Symbols subset: generated by scripts/update-icon-font.cjs */\n@font-face {\n  font-family: 'Material Symbols Outlined';\n  font-style: normal;\n  font-weight: 500;\n  font-display: block;\n  src: url('/fonts/"+file+"') format('woff2');\n}\n";
  const marker=/\/\* Material Symbols subset: generated by scripts\/update-icon-font\.cjs \*\/\n@font-face \{[^}]+\}\n/;
  source=marker.test(source)?source.replace(marker,declaration):source.replace('@config "../tailwind.config.js";', '@config "../tailwind.config.js";\n\n'+declaration);
  fs.writeFileSync(stylesheet,source);console.log('Generated '+icons.length+' symbols, '+font.length+' bytes');
})().catch(error=>{console.error(error.message);process.exitCode=1;});
